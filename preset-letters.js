// ============================================================
//  预设信封 —— 洋灵许愿树（48 封，对应 824 当天每半小时一封）
//
//  824 当天，按【中国时间】每到整点/半点解锁一封、逐封亮起：
//    第 1 封 → 00:00       第 2 封 → 00:30
//    第 3 封 → 01:00       第 4 封 → 01:30
//    ……                   ……
//    第 47 封 → 23:00      第 48 封 → 23:30
//  只能查看，不能编辑。未到点的信是暗的、点了会提示还没开启。
//
//  每封信可以有三种内容，可任意组合（不需要的留空 "" 即可）：
//    title : 信的标题（弹窗顶部显示）
//    text  : 文字内容（想换行用 \n）
//    image : 图片网址；也可以是跟网页一起上传的图片，例如 "./letters/1.jpg"
//    link  : 一个可点击的链接（例如一首歌、一条微博）
//    linkText : 链接显示的文字（不填就显示“点击查看”）
//
//  内容还没到齐前，先放占位即可，之后随时替换重新部署。
//  下面前 3 封是「示范」，让你/客户看到图片、文字、链接长什么样。
// ============================================================

// 半点/整点的时间标签，自动生成 00:00, 00:30, 01:00 ...
function _slotLabel(i){
  const h = Math.floor(i/2);
  const m = (i%2)===0 ? "00" : "30";
  return `${String(h).padStart(2,"0")}:${m}`;
}

window.PRESET_LETTERS = [
  // —— 示范 1：纯文字 ——
  {
    title: "00:00 · 824 快乐",
    text : "洋灵，824 快乐。\n新的一天从这一刻开始，\n第一句想说的话是——\n遇见你们，真好。",
    image: "",
    link : "",
    linkText: ""
  },
  // —— 示范 2：文字 + 图片 ——
  {
    title: "00:30 · 那一天的你们",
    text : "还记得第一次看见你们同框的样子吗？\n就从那一刻起，我们决定一直走下去。",
    image: "https://picsum.photos/600/360",   // ← 换成你们的图片网址或 ./letters/2.jpg
    link : "",
    linkText: ""
  },
  // —— 示范 3：文字 + 链接 ——
  {
    title: "01:00 · 想和你们分享这首歌",
    text : "这首歌，送给此刻打开这封信的你。",
    image: "",
    link : "https://www.youtube.com/",          // ← 换成一首歌 / 一条微博 的链接
    linkText: "▶ 点这里听"
  },

  // —— 其余 45 封：占位，等内容到齐再填 ——
  // （下面用循环生成，你也可以照上面的格式一封封手写覆盖）
];

// 自动补齐到 48 封占位（第 4 封起）
for(let i = window.PRESET_LETTERS.length; i < 48; i++){
  window.PRESET_LETTERS.push({
    title: `${_slotLabel(i)} · 第${i+1}封`,
    text : `（这里放第 ${i+1} 封信的内容）`,
    image: "",
    link : "",
    linkText: ""
  });
}
